inline void text(Image& im, int x, int y, const std::string& s, uint32_t col) {
  for (char ch : s) {
    const char u = char(std::toupper(static_cast<unsigned char>(ch)));
    for (const Glyph& g : kFont)
      if (g.c == u)
        for (int r = 0; r < 7; ++r)
          for (int c = 0; c < 5; ++c)
            if (g.rows[r] >> (4 - c) & 1) put(im, x + c, y + r, col);
    x += 6;
  }
}
inline int text_w(const std::string& s) { return int(s.size()) * 6 - 1; }

