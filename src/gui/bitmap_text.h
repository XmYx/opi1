inline void put(Image& im, int x, int y, uint32_t c) {
  if (x >= 0 && x < im.w && y >= 0 && y < im.h) im.at(x, y) = c;
}
inline void rect(Image& im, int x, int y, int w, int h, uint32_t c) {
  for (int j = y; j < y + h; ++j)
    for (int i = x; i < x + w; ++i) put(im, i, j, c);
}

